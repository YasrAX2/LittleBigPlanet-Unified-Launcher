import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const browser=await chromium.connectOverCDP('http://127.0.0.1:9224');
const context=browser.contexts()[0],page=context.pages()[0];
await page.waitForSelector('.world-bubbles');
assert.equal(new URL(page.url()).hostname,'tauri.localhost');
const invoke=(command,args={})=>page.evaluate(({command,args})=>window.__TAURI_INTERNALS__.invoke(command,args),{command,args});
const before=(await invoke('snapshot')).config;
assert.equal(await page.locator('.pod-backdrop img').getAttribute('src'),'/backgrounds/sackboy.png');
assert.ok(await page.locator('.pod-backdrop img').evaluate(e=>getComputedStyle(e).filter.includes('blur(8px)')));
const results={version:'1.2.1',pictureAndThemeColor:true,packagedOrigin:page.url(),freshAppearance:before.palette,images:false,font:false,persistence:false,offline:false};
assert.equal(before.palette,'black-green');
for(const image of await page.locator('.pod-backdrop img,.world-bubbles img').all())assert.ok(await image.evaluate(e=>e.complete&&e.naturalWidth>100));
results.images=true;
assert.ok(await page.evaluate(()=>document.fonts.check('16px Rubik')));results.font=true;
await page.locator('.appearance-shortcut').click();
await page.getByRole('radio',{name:/Theme color/}).check();
const firstColor=await page.locator('.pod-backdrop').evaluate(e=>getComputedStyle(e).backgroundColor);
await page.getByRole('button',{name:'Cyan & yellow color',exact:true}).click();
assert.equal(await page.locator('.pod-backdrop img').count(),0);
assert.notEqual(await page.locator('.pod-backdrop').evaluate(e=>getComputedStyle(e).backgroundColor),firstColor);
await page.reload();await page.waitForSelector('.world-bubbles');
assert.equal((await invoke('snapshot')).config.palette,'cyan-yellow');assert.equal((await invoke('snapshot')).config.background,'color');results.persistence=true;
await invoke('preferences',{changes:{palette:'black-green',background:'picture',panelOpacity:65}});
await context.setOffline(true);await page.reload();await page.waitForSelector('.world-bubbles');
for(const image of await page.locator('.pod-backdrop img,.world-bubbles img').all())assert.ok(await image.evaluate(e=>e.complete&&e.naturalWidth>100));
await page.locator('.appearance-shortcut').click();
for(const image of await page.locator('.palette-preview img').all())assert.ok(await image.evaluate(e=>e.complete&&e.naturalWidth===84));
assert.ok(await page.evaluate(()=>document.fonts.check('16px Rubik')));results.offline=true;
await context.setOffline(false);
await fs.writeFile('docs/packaged-popit-results.json',JSON.stringify(results,null,2)+'\n');
console.log(JSON.stringify(results));await browser.close();
